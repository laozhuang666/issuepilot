import asyncio

from issuepilot.config import Settings
from issuepilot.github import GitHubClient
from issuepilot.models import AnalysisResponse, FileEvidence, IssueReference
from issuepilot.planner import Planner
from issuepilot.relevance import rank_files


class AnalysisService:
    def __init__(self, settings: Settings, github: GitHubClient | None = None) -> None:
        self.settings = settings
        self.github = github or GitHubClient(settings)
        self.planner = Planner(settings)

    async def close(self) -> None:
        await self.github.close()

    async def analyze(self, issue_url: str) -> AnalysisResponse:
        ref = IssueReference.from_url(issue_url)
        issue, repository = await asyncio.gather(
            self.github.fetch_issue(ref),
            self.github.fetch_repository(ref),
        )
        files = await self.github.fetch_tree(ref, repository.default_branch)
        ranked = rank_files(issue, files, self.settings.max_context_files)

        contents = await asyncio.gather(
            *(
                self.github.fetch_file(ref, file.path, repository.default_branch)
                for file, _, _ in ranked
            ),
            return_exceptions=True,
        )
        evidence: list[FileEvidence] = []
        for (file, score, reasons), content in zip(ranked, contents, strict=True):
            preview = "" if isinstance(content, Exception) else content[:8_000]
            evidence.append(
                FileEvidence(
                    path=file.path, score=round(score, 2), reasons=reasons, preview=preview
                )
            )

        plan, planner_name = await self.planner.create_plan(issue, repository, evidence)
        notice = (
            "Generated with repository evidence and an OpenAI model. Review before implementation."
            if planner_name == "openai"
            else (
                "Generated by the local deterministic planner. "
                "Add OPENAI_API_KEY for deeper analysis."
            )
        )
        return AnalysisResponse(
            issue=issue,
            repository=repository,
            relevant_files=evidence,
            plan=plan,
            planner=planner_name,
            notice=notice,
        )
